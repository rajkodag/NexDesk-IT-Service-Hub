-- 1. Users Table & Sequence
CREATE TABLE NX_USERS (
    USER_ID NUMBER PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) UNIQUE NOT NULL,
    USER_PASSWORD VARCHAR2(255) NOT NULL,
    USER_ROLE VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE SEQUENCE NX_USER_SEQ START WITH 1 INCREMENT BY 1;

-- 2. Technicians Table & Sequence
CREATE TABLE NX_TECHNICIANS (
    TECHNICIAN_ID NUMBER PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) UNIQUE NOT NULL,
    SPECIALIZATION VARCHAR2(100),
    STATUS VARCHAR2(20) DEFAULT 'AVAILABLE',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE SEQUENCE NX_TECH_SEQ START WITH 1 INCREMENT BY 1;

-- 3. Tickets Table & Sequence
CREATE TABLE NX_TICKETS (
    TICKET_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    TECHNICIAN_ID NUMBER,
    TITLE VARCHAR2(200) NOT NULL,
    DESCRIPTION VARCHAR2(2000) NOT NULL,
    CATEGORY VARCHAR2(50) DEFAULT 'General',
    PRIORITY VARCHAR2(20) DEFAULT 'MEDIUM',
    STATUS VARCHAR2(20) DEFAULT 'OPEN',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DUE_AT TIMESTAMP,
    RESOLVED_AT TIMESTAMP,
    DIAGNOSTICS_DATA VARCHAR2(2000),
    IMPACT_SCORE NUMBER,
    CONSTRAINT FK_TICKET_USER FOREIGN KEY (USER_ID) REFERENCES NX_USERS(USER_ID),
    CONSTRAINT FK_TICKET_TECH FOREIGN KEY (TECHNICIAN_ID) REFERENCES NX_TECHNICIANS(TECHNICIAN_ID)
);
CREATE SEQUENCE NX_TICKET_SEQ START WITH 1 INCREMENT BY 1;

-- 4. Ticket Comments & Discussions Table & Sequence
CREATE TABLE NX_TICKET_COMMENTS (
    COMMENT_ID NUMBER PRIMARY KEY,
    TICKET_ID NUMBER NOT NULL,
    USER_ID NUMBER,
    AUTHOR_NAME VARCHAR2(100),
    AUTHOR_ROLE VARCHAR2(20),
    MESSAGE VARCHAR2(2000) NOT NULL,
    IS_INTERNAL NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_COMMENT_TICKET FOREIGN KEY (TICKET_ID) REFERENCES NX_TICKETS(TICKET_ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMMENT_USER FOREIGN KEY (USER_ID) REFERENCES NX_USERS(USER_ID)
);
CREATE SEQUENCE NX_COMMENT_SEQ START WITH 1 INCREMENT BY 1;

-- 5. Audit Logging Table & Sequence
CREATE TABLE NX_AUDIT_LOGS (
    LOG_ID NUMBER PRIMARY KEY,
    TICKET_ID NUMBER,
    ACTION VARCHAR2(100) NOT NULL,
    PERFORMED_BY VARCHAR2(100) NOT NULL,
    USER_ROLE VARCHAR2(30),
    DETAILS VARCHAR2(2000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE SEQUENCE NX_AUDIT_SEQ START WITH 1 INCREMENT BY 1;

